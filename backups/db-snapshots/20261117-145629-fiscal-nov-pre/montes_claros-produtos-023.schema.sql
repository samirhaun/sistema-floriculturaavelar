CREATE TABLE `produtos` (
  `id` int(11) NOT NULL AUTO_INCREMENT,
  `categorias_id` int(11) DEFAULT '0',
  `titulo` varchar(255) DEFAULT NULL,
  `nome_tag` varchar(155) NOT NULL,
  `descricao` text,
  `nfce_ncm` varchar(8) DEFAULT NULL,
  `nfce_csosn` varchar(4) DEFAULT NULL,
  `nfce_pis_cst` varchar(2) DEFAULT NULL,
  `nfce_cofins_cst` varchar(2) DEFAULT NULL,
  `nfce_cfop` varchar(4) DEFAULT NULL,
  `grupos_fiscais_nfce_id` int(11) DEFAULT NULL,
  `grupo_fiscal_sugerido_id` int(11) DEFAULT NULL,
  `grupo_fiscal_sugestao_confianca` varchar(10) DEFAULT NULL,
  `grupo_fiscal_sugestao_origem` varchar(50) DEFAULT NULL,
  `valor` decimal(10,2) DEFAULT NULL,
  `valor_custo` decimal(10,2) DEFAULT NULL,
  `valor_forma_pagamento` varchar(100) DEFAULT NULL,
  `imagem` text,
  `valor_antigo` decimal(10,2) DEFAULT NULL,
  `estoque` int(11) DEFAULT NULL,
  `comprimento_embalagem` int(11) DEFAULT NULL,
  `altura_embalagem` int(11) DEFAULT NULL,
  `largura_embalagem` int(11) DEFAULT NULL,
  `peso` decimal(6,3) DEFAULT NULL,
  `ativo` tinyint(4) DEFAULT '1' COMMENT '1: sim   2 : não',
  `categoria_sexo` int(11) NOT NULL COMMENT '1 = MASCULINO 2 = FEMININO',
  `destaque` tinyint(4) NOT NULL DEFAULT '0' COMMENT '1: sim 0:nao',
  `detalhes` text NOT NULL,
  `valor_frete` varchar(100) DEFAULT NULL,
  `tamanhos` int(11) DEFAULT '0',
  `marcas_id` int(11) DEFAULT NULL,
  `novo` int(11) NOT NULL DEFAULT '0',
  `porcentagem_desconto` int(11) DEFAULT NULL,
  `alerta_estoque_minimo` int(11) DEFAULT NULL,
  `disponivel_site` int(11) DEFAULT '0',
  `exibir_em_pedidos` int(11) DEFAULT '1',
  PRIMARY KEY (`id`),
  KEY `fk_produtos_categorias1_idx` (`categorias_id`),
  KEY `nome_tag` (`nome_tag`),
  KEY `idx_produtos_grupo_fiscal_nfce` (`grupos_fiscais_nfce_id`),
  KEY `idx_produtos_grupo_fiscal_sugerido` (`grupo_fiscal_sugerido_id`),
  CONSTRAINT `fk_produtos_categorias1` FOREIGN KEY (`categorias_id`) REFERENCES `categorias` (`id`) ON DELETE NO ACTION ON UPDATE NO ACTION,
  CONSTRAINT `fk_produtos_grupo_fiscal_nfce` FOREIGN KEY (`grupos_fiscais_nfce_id`) REFERENCES `grupos_fiscais_nfce` (`id`),
  CONSTRAINT `fk_produtos_grupo_fiscal_sugerido` FOREIGN KEY (`grupo_fiscal_sugerido_id`) REFERENCES `grupos_fiscais_nfce` (`id`)
) ENGINE=InnoDB AUTO_INCREMENT=1087 DEFAULT CHARSET=utf8